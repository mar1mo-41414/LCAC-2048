#ifndef SPAWN_BIAS_H
#define SPAWN_BIAS_H
#include <stdint.h>

// 2048 4.0.8 がタイルを出すマスの「出やすさ」。1000 = 一様 (全マス同じ)。
// 添字は y * 4 + x、y = 0 が画面の最下段 (ログの盤面の並びと同じ)。
//
// 出どころ: 実機の Documents/LCAC-2048.log にある `spawns` 行。
// v3.9 の 119 ゲーム / 209,292 回の出現について、`count` (そのマスに出た回数) を
// `chance` (そのマスが空いていた回数) で割り、16 マスの平均で割った値。
// 一様抽選からのずれは χ² = 755 (df = 15) で、偶然とは言えない。
// 外周は一様より 3〜7% 出やすく、中央の 2×2 は 10〜11% 出にくい。
//
// 注意: `chance` は「空いていた回数」なので、空きにくいマス (角・辺) の値は
// 空きやすいマスとは違う盤面で測られている。位置の効果と盤面の形の効果が
// 混ざっている可能性がある。左右で 2〜3% 違うが、これは 1 マスあたりの
// 標本が 13,000 回程度なので誤差の範囲に近い。
static const int32_t kSpawnWeight[16] = {
    1047, 1009, 1042, 1071, // y = 0 (最下段)
    995, 886, 899, 1020,
    1006, 888, 897, 1035,
    1040, 1007, 1016, 1068  // y = 3 (最上段)
};

#endif
